"""Generate docs/tool-reference.md from the registered tools, resources and prompts (SOW D9).

    python scripts/generate_tool_reference.py [--profile unified] [--out docs/tool-reference.md]

Reads the same wire objects the interface baseline freezes, so the reference and the contract
cannot disagree. Requires the project dependencies.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from evs_cadsr_mcp import INTERFACE_VERSION, __version__  # noqa: E402
from evs_cadsr_mcp.server.baseline import collect_profile  # noqa: E402


def _args_table(schema: dict) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    if not props:
        return "_no arguments_\n"
    lines = ["| argument | type | required | description |", "|---|---|---|---|"]
    for name, p in props.items():
        typ = p.get("type") or ("/".join(x.get("type", "?") for x in p.get("anyOf", [])) if "anyOf" in p else ("enum" if "enum" in p else "object"))
        if "enum" in p:
            typ += " (" + " \\| ".join(map(str, p["enum"])) + ")"
        default = f" Default `{p['default']}`." if "default" in p and p["default"] not in (None, [], {}) else ""
        desc = (p.get("description") or "").replace("\n", " ").replace("|", "\\|")
        lines.append(f"| `{name}` | {typ} | {'yes' if name in required else 'no'} | {desc}{default} |")
    return "\n".join(lines) + "\n"


def _result_fields(schema: dict | None) -> str:
    if not schema:
        return ""
    res = (schema.get("properties") or {}).get("result") or {}
    ref = res.get("$ref") or (res.get("items") or {}).get("$ref")
    defs = schema.get("$defs") or {}
    target = defs.get(ref.rsplit("/", 1)[-1]) if ref else res
    props = (target or {}).get("properties") or {}
    if not props:
        return ""
    shape = "list of " if "items" in res else ""
    names = ", ".join(f"`{k}`" for k in props)
    return f"**Result:** {shape}object with {names}.\n"


async def main(profile: str, out: Path) -> None:
    data = await collect_profile(profile)
    lines = [f"# Tool reference — profile `{profile}`", "", f"Server {__version__}, interface baseline {INTERFACE_VERSION}. Generated by `scripts/generate_tool_reference.py`; do not edit by hand.", "",
             "Every tool returns an envelope `{result, provenance[], page?, truncation?, warnings[], meta}`; errors are tool errors whose message is a JSON `{error: {code, message, details, retryable, correlationId}}`.", ""]
    groups = {"evs_": "EVS (NCI Thesaurus)", "cadsr_": "caDSR (Common Data Elements)", "map_": "Mapping (CDE ↔ NCIt, models)"}
    for prefix, heading in groups.items():
        tools = {n: t for n, t in data["tools"].items() if n.startswith(prefix)}
        if not tools:
            continue
        lines += [f"## {heading}", ""]
        for name, t in tools.items():
            lines += [f"### `{name}`" + (f" — {t['title']}" if t.get("title") else ""), "", (t.get("description") or "").strip(), ""]
            ann = t.get("annotations") or {}
            hints = [k for k in ("readOnlyHint", "idempotentHint", "openWorldHint") if ann.get(k)]
            if hints:
                lines += ["Annotations: " + ", ".join(hints) + ("; destructiveHint=false" if ann.get("destructiveHint") is False else ""), ""]
            lines += [_args_table(t.get("inputSchema") or {}), _result_fields(t.get("outputSchema")), ""]
    if data["resources"] or data["resourceTemplates"]:
        lines += ["## Resources", "", "| uri | name | description |", "|---|---|---|"]
        for uri, r in {**data["resources"], **data["resourceTemplates"]}.items():
            lines.append(f"| `{r.get('uri') or r.get('uriTemplate') or uri}` | {r.get('name', '')} | {(r.get('description') or '').strip()} |")
        lines.append("")
    if data["prompts"]:
        lines += ["## Prompts", "", "| name | arguments | description |", "|---|---|---|"]
        for name, p in data["prompts"].items():
            args = ", ".join(f"`{a['name']}`" + ("" if a.get("required") else "?") for a in p.get("arguments") or [])
            lines.append(f"| `{name}` | {args} | {(p.get('description') or '').strip()} |")
        lines.append("")
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(data['tools'])} tools)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", default="unified")
    ap.add_argument("--out", default=str(ROOT / "docs" / "tool-reference.md"))
    a = ap.parse_args()
    asyncio.run(main(a.profile, Path(a.out)))
